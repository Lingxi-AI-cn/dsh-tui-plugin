/** Immutable runtime catalogs; the English map is the fallback contract. */
export const TUI_LOCALE_CATALOG: Readonly<Record<TuiLocale, Readonly<Record<TuiMessageKey, string>>>> = Object.freeze({
  en: EN_MESSAGES,
  zh: ZH_MESSAGES,
})

/** Validate an untrusted settings value without silently selecting another locale. */
export function isTuiLocale(value: unknown): value is TuiLocale {
  return typeof value === 'string' && (TUI_LOCALES as readonly string[]).includes(value)
}

/**
 * Resolve one catalog message, falling back to English for missing translated keys.
 * @param locale - locale whose catalog should be selected.
 * @param key - message key in the TUI catalog.
 * @param params - optional interpolation values.
 * @returns the terminal-safe localized message.
 */
export function tuiMessage(locale: TuiLocale, key: TuiMessageKey, params: TuiMessageParams = {}): string {
  const localized = TUI_LOCALE_CATALOG[locale]
  const template = Object.hasOwn(localized, key) ? localized[key] : EN_MESSAGES[key]
  return terminalSafe(template.replace(/\{([a-z][a-z0-9_]*)\}/giu, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : terminalSafe(String(value))
  }))
}

/**
 * Return a human-readable locale label in the selected target locale.
 * @param locale - locale represented by the label.
 * @param target - locale used to render the label.
 * @returns the localized language label.
 */
export function tuiLocaleLabel(locale: TuiLocale, target: TuiLocale = locale): string {
  return tuiMessage(target, locale === 'zh' ? 'language.chinese' : 'language.english')
}

/** Localize a first-party interaction context while retaining unknown owner labels. */
export function tuiInteractionContextLabel(context: string, locale: TuiLocale): string {
  const key = `help.context.${context}` as TuiMessageKey
  return Object.hasOwn(TUI_LOCALE_CATALOG.en, key) ? tuiMessage(locale, key) : context
}

const HOST_COMMAND_DESCRIPTION_FALLBACKS: Readonly<Record<string, {
  readonly description: string
  readonly key: Extract<TuiMessageKey, `command.${string}`>
}>> = Object.freeze({
  compact: { description: 'Compact older conversation history', key: 'command.compact' },
  feedback: { description: 'record feedback about this session', key: 'command.feedback' },
  goal: { description: 'set or view the goal for a long-running task', key: 'command.goal' },
  permission: {
    description: 'Switch the permission preset (sandbox mode + approval policy)',
    key: 'command.permission',
  },
  plan: { description: 'Enter or leave plan mode', key: 'command.plan' },
})

/**
 * Resolve a command summary with the command owner's stable English fallback.
 * @param command - command descriptor or completion node.
 * @param locale - locale requested by the TUI.
 * @returns the best available localized summary.
 */
export function tuiCommandDescription(
  command: CommandDescriptor | CommandCompletionNode,
  locale: TuiLocale,
): string {
  const metadata = command as unknown as {
    readonly name: string
    readonly completion?: { readonly descriptions?: Readonly<Record<string, string>> }
    readonly descriptions?: Readonly<Record<string, string>>
    readonly description: string
  }
  const descriptions = metadata.completion?.descriptions ?? metadata.descriptions
  const localized = descriptions?.[locale]
  if (localized !== undefined) return localized
  const fallback = HOST_COMMAND_DESCRIPTION_FALLBACKS[metadata.name]
  if (locale !== 'en' && fallback?.description === metadata.description) return tuiMessage(locale, fallback.key)
  return descriptions?.en ?? metadata.description
}

/**
 * Return first-party localized summaries contributed by the TUI command owner.
 * @param key - first-party command message key.
 * @returns immutable English and Chinese summaries.
 */
export function tuiCommandDescriptions(key: Extract<TuiMessageKey, `command.${string}`>): Readonly<Record<TuiLocale, string>> {
  return Object.freeze({ en: tuiMessage('en', key), zh: tuiMessage('zh', key) })
}

const TuiLocaleContext = createContext<TuiLocale>('en')

/**
 * Provide the current process-local locale to the Ink tree.
 * @param props - locale value and optional Ink children.
 * @returns the locale context provider element.
 */
export function TuiLocaleProvider(props: {
  readonly locale: TuiLocale
  readonly children?: ReactNode
}): React.ReactElement {
  const { locale, children } = props
  return React.createElement(TuiLocaleContext.Provider, { value: locale }, children)
}

/**
 * Read the current locale selected by the TUI settings owner.
 * @returns the active TUI locale.
 */
export function useTuiLocale(): TuiLocale {
  return useContext(TuiLocaleContext)
}
